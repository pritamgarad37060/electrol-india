import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import '../js/result-math.js';
const coverage=globalThis.ElectrolResultMath.pollingCoverage;
const poll={rosterComplete:true,c:[['A',0,70],['B',1,30]],ballots:100,electors:200};
const uncontested={status:'unopposed',rosterComplete:false,c:[['C',0,null]]};
assert.deepEqual(coverage([poll,uncontested]),{complete:true,unopposed:1,polled:1,ballots:100,electors:200,turnout:50});
assert.equal(coverage([poll,{...poll,rosterComplete:false}]).complete,false);
assert.equal(coverage([{...poll,c:[['A',0,null]]}]).complete,false);
assert.equal(coverage([{...poll,c:[['A',0,-1]]}]).complete,false);
assert.equal(coverage([uncontested]).complete,false);
assert(Number.isNaN(coverage([uncontested]).turnout));
assert(Number.isNaN(coverage([{...poll,ballots:201}]).turnout));
const catalog=JSON.parse(await fs.readFile('data/catalog.json','utf8'));
const entry=catalog.find(e=>e.id==='lok|All India|2024');
const data=JSON.parse(await fs.readFile('.'+entry.file,'utf8'));
const national=coverage(data.seats);
assert.equal(national.complete,true);assert.equal(national.polled,542);assert.equal(national.unopposed,1);
